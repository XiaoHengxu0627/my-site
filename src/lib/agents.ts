export function buildWeeklyReportDeepDivePrompt(topic: string): string {
  return `你是一个资深的 AI 前沿技术分析专家。用户对之前周报中的某一条更新感兴趣，希望深入展开。

## 用户想深入了解的更新
${topic}

## 输出要求
- **技术原理**：这个能力背后用到了什么关键技术路线（用易懂的语言解释）
- **竞品对比**：同样方向下，有哪些竞争方案或替代技术，各自的优劣势
- **落地路径**：这个能力可以如何在实际产品中落地应用，第一阶段切入点和评估指标是什么
- **未来展望**：这个技术方向下一阶段可能的发展趋势是什么

## 结尾
附一个可以进一步追问的问题。`
}

export function isWeeklyReportQuery(text: string): boolean {
  const keywords = ['周报', 'weekly', 'ai周报', 'AI周报', '行业周报', '本周ai', '本周 AI', 'AI 周报', 'ai 周报']
  const lower = text.toLowerCase()
  return keywords.some((k) => lower.includes(k.toLowerCase()))
}

export function isDeepDiveQuery(text: string): boolean {
  const keywords = ['深入', '展开', '详细说说', '具体讲', '展开说说', 'deep dive', 'tell me more', '讲一下', '展开讲']
  const lower = text.toLowerCase()
  return keywords.some((k) => lower.includes(k.toLowerCase()))
}
